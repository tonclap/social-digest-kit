#!/usr/bin/env python3
"""
Разбор позиционных аргументов, общий для скриптов в этой папке.

Зачем отдельный файл: каждый скрипт начинался со строки

    args = [a for a in sys.argv[1:] if not a.startswith("--")]

и брал из неё путь к базе. Значение флага под это правило не подпадает —
оно не начинается с "--", — поэтому `due_today.py --network vk` понимал "vk"
как имя файла базы, а `sqlite3.connect` молча заводил пустой файл с таким
именем и отвечал «к проверке 0 человек». Уверенный и неверный ответ вместо
ошибки: пустая очередь на прогоне выглядит как штатный результат.

positionals() отбрасывает и сами флаги, и значения тех из них, что значение
принимают. Список таких флагов скрипт передаёт сам — он и так их знает.
"""


def positionals(argv, value_flags=()):
    """Позиционные аргументы из argv (обычно sys.argv[1:]).

    value_flags — флаги, за которыми идёт отдельным словом значение
    ("--network", "--date"). Форма "--date=2026-09-15" значение несёт в себе,
    следующее слово у неё не съедается.
    """
    value_flags = set(value_flags)
    out, skip_next = [], False
    for a in argv:
        if skip_next:
            skip_next = False
            continue
        if a.startswith("--"):
            skip_next = a in value_flags
            continue
        out.append(a)
    return out


def require_db(path):
    """Путь к существующей базе — или внятный отказ.

    sqlite3.connect() создаёт пустой файл, если его нет: опечатка в пути
    оборачивалась не ошибкой, а пустой базой рядом и падением на «no such
    table» несколькими строками ниже (а у скриптов, которые до таблиц не
    доходят, — уверенным ответом «никого не нашлось»). Та же логика, что в
    build_db.py: молча заводить пустую базу вместо работы — хуже, чем отказ.
    """
    import os
    import sys

    if not os.path.exists(path):
        sys.exit(f"базы нет: {path}\n"
                 f"(укажите путь первым аргументом; новую базу заводит build_db.py)")
    return path
